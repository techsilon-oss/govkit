#!/usr/bin/env node
/**
 * build-template-history — the hash of every owned template in every govkit release.
 *
 * Writes skills/govkit-init/template-history.json, which upgrade.mjs uses to tell an outdated file
 * (matches an older release) from an edited one (matches none). Run it as part of every release,
 * after the version bump: a test fails if the index lacks the current templates.
 *
 * Releases before 0.4.0 were never tagged, so they are listed by commit. 0.3.0 shipped twice under
 * one version number — #7 changed supabase.mjs without a bump — so the second is "0.3.0+#7".
 * From 0.4.0 on, every release is a v<version> tag.
 *
 * Usage (from the govkit repo root):  node tools/build-template-history.mjs
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { OWNED, TEMPLATES, pluginVersion, sha256 } from "../skills/govkit-init/upgrade.mjs";

const UNTAGGED = [
  ["0.1.0", "af967cf"],
  ["0.2.0", "d072bb7"],
  ["0.2.1", "90396dc"],
  ["0.3.0", "7958f49"],
  ["0.3.0+#7", "f264025"],
];

const git = (args) => {
  try {
    return execFileSync("git", args, { encoding: "utf-8", stdio: ["ignore", "pipe", "ignore"] });
  } catch {
    return null;
  }
};

const semver = (v) => v.replace(/^v/, "").split(".").map(Number);
const bySemver = (a, b) => {
  const [x, y] = [semver(a), semver(b)];
  return x[0] - y[0] || x[1] - y[1] || x[2] - y[2];
};

const tagged = (git(["tag", "--list", "v*"]) ?? "")
  .split("\n")
  .filter((t) => /^v\d+\.\d+\.\d+$/.test(t))
  .sort(bySemver)
  .map((t) => [t.slice(1), t]);

const current = pluginVersion();
const releases = [...UNTAGGED, ...tagged].filter(([v]) => v !== current);

const index = { $comment: "Generated by tools/build-template-history.mjs. Do not edit by hand.", $releases: [] };
const add = (version, path, text) => {
  const hash = sha256(text);
  index[path] ??= [];
  const hit = index[path].find((h) => h.sha256 === hash);
  if (hit) hit.versions.push(version);
  else index[path].push({ sha256: hash, versions: [version] });
};

for (const [version, ref] of releases) {
  index.$releases.push(version);
  for (const entry of OWNED) {
    const text = git(["show", `${ref}:skills/govkit-init/templates/${entry.template}`]);
    if (text !== null) add(version, entry.path, text);
    // A file renamed since: index that release under its old name, which is what a repo
    // initialised then still has on disk.
    const old = entry.renamedFrom;
    const oldText = old ? git(["show", `${ref}:skills/govkit-init/templates/${old.template}`]) : null;
    if (oldText !== null) add(version, old.path, oldText);
  }
}

// The working tree is the release being built.
index.$releases.push(current);
for (const entry of OWNED) add(current, entry.path, readFileSync(join(TEMPLATES, entry.template), "utf-8"));

writeFileSync("skills/govkit-init/template-history.json", `${JSON.stringify(index, null, 2)}\n`);
console.log(`template-history.json: ${index.$releases.length} releases, current ${current}`);
for (const entry of OWNED) console.log(`  ${entry.path.padEnd(34)} ${index[entry.path]?.length ?? 0} distinct version(s)`);
